#!/usr/bin/env bash
# Reusable helpers for the interactive VPS installer. Never source the env file.

log()   { printf '\033[1;32m[DeAIfy]\033[0m %s\n' "$*" >&2; }
warn()  { printf '\033[1;33m[注意]\033[0m %s\n' "$*" >&2; }
error() { printf '\033[1;31m[错误]\033[0m %s\n' "$*" >&2; exit 1; }

# Bash 4.2 is available on supported CentOS/RHEL installations.
declare -A CFG=()
readonly ENV_KEYS=(
  MYSQL_MODE FRONTEND_ORIGIN API_PUBLIC_ORIGIN API_BIND_PORT
  MYSQL_HOST MYSQL_PORT MYSQL_DATABASE MYSQL_USER MYSQL_PASSWORD MYSQL_ROOT_PASSWORD
  MYSQL_SSL_MODE MYSQL_SSL_CA_B64 RESULT_ENCRYPTION_KEY_HEX PROCESSOR_SHARED_TOKEN
  FREE_USES_PER_DAY TRUSTED_PROXY_CIDRS REGISTRATION_ENABLED RECOVERY_ENABLED
  PAYMENTS_ENABLED MERCHANT_APPROVED PAYMENT_PROVIDER CREEM_MODE CREEM_API_KEY CREEM_WEBHOOK_SECRET CREEM_PRODUCTS_JSON XUNHU_APPID XUNHU_SECRET XUNHU_GATEWAY
  SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASSWORD SMTP_FROM TURNSTILE_SECRET
  TURNSTILE_SITE_KEY OTP_SECRET
)

load_env() {
  local line key value
  [[ -f "$ENV_FILE" ]] || return 0
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" =~ ^([A-Z][A-Z0-9_]*)=(.*)$ ]] || continue
    key="${BASH_REMATCH[1]}"; value="${BASH_REMATCH[2]}"
    if [[ "${value:0:1}" == "'" && "${value: -1}" == "'" ]]; then
      value="${value:1:${#value}-2}"
      value="${value//\\\'/\'}"
    fi
    CFG["$key"]="$value"
  done < "$ENV_FILE"
}

get_value() { printf '%s' "${CFG[$1]-}"; }
keep_default() { [[ -n "${CFG[$1]-}" ]] || CFG["$1"]="$2"; }
random_hex() {
  if command -v openssl >/dev/null 2>&1; then openssl rand -hex 32
  else od -An -tx1 -N32 /dev/urandom | tr -d ' \n'; fi
}

ask() {
  local label="$1" default="${2-}" response
  if [[ -n "$default" ]]; then
    printf '%s [%s]: ' "$label" "$default" >&2
  else
    printf '%s: ' "$label" >&2
  fi
  IFS= read -r response || error '输入被中断；没有写入任何新配置。'
  REPLY="${response:-$default}"
}
ask_secret() {
  local label="$1" exists="${2:-false}" value
  if [[ "$exists" == true ]]; then printf '%s（回车保留已有密钥）: ' "$label" >&2
  else printf '%s: ' "$label" >&2; fi
  IFS= read -r -s value || error '密钥输入被中断；配置未更改。'
  [[ -t 0 ]] && printf '\n' >&2 || true
  REPLY="$value"
}
confirm() {
  local label="$1" default="${2:-N}" answer
  ask "$label (y/n)" "$default"
  answer="${REPLY,,}"
  case "$answer" in y|yes) return 0;; n|no) return 1;; *) error '请输入 y 或 n。';; esac
}

require_value() { [[ -n "$1" ]] || error "$2 不能为空。"; }
validate_origin() {
  [[ "$1" =~ ^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?$ ]] || error "$2 必须是 HTTPS 域名 Origin（无路径和尾部 /）。"
  [[ "$1" != *..* && "$1" != *.-* ]] || error "$2 域名无效。"
}
validate_host() {
  [[ "$1" =~ ^[A-Za-z0-9._-]+$ ]] || error "$2 格式不正确，只输入地址，不要带端口或协议。"
}
validate_identifier() {
  [[ "$1" =~ ^[A-Za-z0-9_]{1,32}$ ]] || error "$2 只允许 1–32 位英文、数字、下划线。"
}
validate_port() {
  [[ "$1" =~ ^[0-9]{1,5}$ ]] && (( 10#$1 >= 1 && 10#$1 <= 65535 )) || error "$2 不是有效端口。"
}
validate_secret_line() {
  [[ "$1" != *$'\n'* && "$1" != *$'\r'* ]] || error '配置值不能包含换行符。'
}

# Compose dotenv supports single-quoted literals (no ${VAR} expansion in secrets).
quote_dotenv() {
  validate_secret_line "$1"
  local escaped="${1//\'/\\\'}"
  printf "'%s'" "$escaped"
}

save_env() {
  local tmp key timestamp
  tmp="$(mktemp "${ENV_FILE}.tmp.XXXXXXXX")" || error '无法创建临时配置文件。'
  chmod 600 "$tmp"
  {
    printf '# Generated by scripts/setup.sh. NEVER commit this file.\n'
    for key in "${ENV_KEYS[@]}"; do
      printf '%s=' "$key"
      quote_dotenv "${CFG[$key]-}"
      printf '\n'
    done
  } > "$tmp" || { rm -f "$tmp"; error '写入配置失败。'; }
  if [[ -f "$ENV_FILE" ]]; then
    timestamp="$(date -u +%Y%m%d%H%M%S)"
    cp -p "$ENV_FILE" "${ENV_FILE}.backup.${timestamp}.$$" || { rm -f "$tmp"; error '备份原配置失败。'; }
    chmod 600 "${ENV_FILE}.backup.${timestamp}.$$"
  fi
  mv -f "$tmp" "$ENV_FILE" || error '无法替换配置文件。'
  chmod 600 "$ENV_FILE"
}

check_tools() {
  command -v docker >/dev/null 2>&1 || error '未找到 Docker。请先安装 Docker Engine 与 Compose V2。'
  docker compose version >/dev/null 2>&1 || error '未找到 docker compose V2，请先安装 Compose 插件。'
  docker info >/dev/null 2>&1 || error '无法连接 Docker daemon。检查权限或启动 Docker 服务。'
  command -v curl >/dev/null 2>&1 || error '未找到 curl。请先安装 curl。'
}

compose() { (cd "$ROOT" && docker compose --env-file "$ENV_FILE" -f docker-compose.commercial.yml "$@"); }

show_status() {
  [[ -f "$ENV_FILE" ]] || error '还没有配置。请先运行 bash scripts/setup.sh。'
  log "配置已存在：$ENV_FILE（敏感值不会显示）"
  log "MySQL: ${CFG[MYSQL_MODE]:-unknown} · API: ${CFG[API_PUBLIC_ORIGIN]:-unknown}"
  log "公开注册：${CFG[REGISTRATION_ENABLED]:-false} · 真实支付：${CFG[PAYMENTS_ENABLED]:-false}"
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    compose config --quiet && log 'Docker Compose 配置检查通过。'
    compose ps || true
  fi
}
